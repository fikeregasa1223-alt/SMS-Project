<?php
declare(strict_types=1);

require_once __DIR__ . '/../../config/config.php';

sms_session_start();
require_login();
require_permission('view_marks');

$examId    = (int) ($_GET['exam_id'] ?? 0);
$studentId = (int) ($_GET['student_id'] ?? 0);

$exam = Database::fetch(
    "SELECT e.*, g.name AS grade_name, g.level AS grade_level,
            ay.name AS year_name, t.name AS term_name
     FROM examinations e
     JOIN grades g ON g.id = e.grade_id
     JOIN academic_years ay ON ay.id = e.academic_year_id
     JOIN terms t ON t.id = e.term_id
     WHERE e.id = ?",
    [$examId]
);
if (!$exam) { flash_set('error', 'Examination not found.'); redirect(url('admin/examinations/index.php')); }

$student = Database::fetch("SELECT * FROM students WHERE id = ?", [$studentId]);
if (!$student) { flash_set('error', 'Student not found.'); redirect(url('admin/examinations/index.php')); }

$enr = Database::fetch(
    "SELECT e.*, g.name AS grade_name, sec.name AS section_name
     FROM enrollments e
     JOIN grades g ON g.id = e.grade_id
     JOIN sections sec ON sec.id = e.section_id
     WHERE e.student_id = ? AND e.academic_year_id = ? AND e.status = 'active' LIMIT 1",
    [$studentId, (int)$exam['academic_year_id']]
);

$marks = Database::fetchAll(
    "SELECT m.*, sub.code AS subject_code, sub.name AS subject_name
     FROM marks m
     JOIN subjects sub ON sub.id = m.subject_id
     WHERE m.student_id = ? AND m.examination_id = ?
     ORDER BY sub.name ASC",
    [$studentId, $examId]
);

$totalScore = 0; $totalMax = 0;
foreach ($marks as $m) {
    if ($m['score'] !== null) { $totalScore += (float)$m['score']; }
    $totalMax += (float)$m['max_mark'];
}
$overallPct = $totalMax > 0 ? round(($totalScore / $totalMax) * 100, 2) : 0;
$overall    = resolve_grade($overallPct, (int)$exam['grade_id']);

$schoolName  = setting('school_name', 'SMS Secondary School');
$schoolAddr  = setting('school_address', '');
$schoolPhone = setting('school_phone', '');
$schoolEmail = setting('school_email', '');
$reportHeader= setting('report_header', 'Official Academic Report');
$reportFooter= setting('report_footer', 'Generated by SMS');

$name = trim(($student['first_name'] ?? '') . ' ' . ($student['middle_name'] ?? '') . ' ' . ($student['last_name'] ?? ''));
?>
<!doctype html>
<html lang="en">
<head>
    <meta charset="utf-8">
    <title>Report Card — <?= e($name) ?></title>
    <link href="<?= url('assets/css/app.css') ?>" rel="stylesheet">
    <link href="<?= url('assets/css/examinations.css') ?>" rel="stylesheet">
    <link href="https://cdn.jsdelivr.net/npm/bootstrap-icons@1.11.3/font/bootstrap-icons.min.css" rel="stylesheet">
</head>
<body>
<div class="report-card">
    <div class="rc-header">
        <h1><?= e($schoolName) ?></h1>
        <div class="sub">
            <?= e($schoolAddr) ?>
            <?php if ($schoolPhone): ?> · <?= e($schoolPhone) ?><?php endif; ?>
            <?php if ($schoolEmail): ?> · <?= e($schoolEmail) ?><?php endif; ?>
        </div>
    </div>

    <div class="rc-title"><?= e($reportHeader) ?></div>

    <div class="info-grid">
        <div class="row"><span>Student Name</span><strong><?= e($name) ?></strong></div>
        <div class="row"><span>Student Code</span><strong><?= e($student['student_code']) ?></strong></div>
        <div class="row"><span>Admission No</span><strong><?= e($student['admission_no']) ?></strong></div>
        <div class="row"><span>Grade</span><strong><?= e($enr['grade_name'] ?? $exam['grade_name']) ?></strong></div>
        <div class="row"><span>Section</span><strong><?= e($enr['section_name'] ?? '—') ?></strong></div>
        <div class="row"><span>Academic Year</span><strong><?= e($exam['year_name']) ?></strong></div>
        <div class="row"><span>Term</span><strong><?= e($exam['term_name']) ?></strong></div>
        <div class="row"><span>Examination</span><strong><?= e($exam['name']) ?></strong></div>
    </div>

    <table>
        <thead>
            <tr>
                <th style="width:40px;">#</th>
                <th style="width:100px;">Code</th>
                <th>Subject</th>
                <th style="width:80px;">Score</th>
                <th style="width:80px;">Max</th>
                <th style="width:80px;">%</th>
                <th style="width:70px;">Grade</th>
            </tr>
        </thead>
        <tbody>
        <?php $i = 1; foreach ($marks as $m): ?>
            <tr>
                <td><?= $i++ ?></td>
                <td><?= e($m['subject_code']) ?></td>
                <td><?= e($m['subject_name']) ?></td>
                <td><?= $m['score'] !== null ? e((string)$m['score']) : 'Absent' ?></td>
                <td><?= e((string)$m['max_mark']) ?></td>
                <td><?= $m['percentage'] !== null ? e((string)$m['percentage']) . '%' : '—' ?></td>
                <td><strong><?= e((string)($m['grade_letter'] ?? '—')) ?></strong></td>
            </tr>
        <?php endforeach; ?>
        <?php if (!$marks): ?>
            <tr><td colspan="7" style="text-align:center;color:#888;">No marks recorded.</td></tr>
        <?php endif; ?>
        </tbody>
        <?php if ($marks): ?>
        <tfoot>
            <tr class="summary-row">
                <td colspan="3">Overall</td>
                <td><?= e((string)$totalScore) ?></td>
                <td><?= e((string)$totalMax) ?></td>
                <td><?= $overallPct ?>%</td>
                <td><?= e((string)($overall['letter'] ?? '—')) ?></td>
            </tr>
        </tfoot>
        <?php endif; ?>
    </table>

    <div class="remarks">
        <strong>Remark:</strong>
        <?= e($overall['remark'] ?? 'No remark available.') ?>
        — Overall percentage: <strong><?= $overallPct ?>%</strong>
    </div>

    <div class="signatures">
        <div>Class Teacher</div>
        <div>Head of School</div>
        <div>Parent / Guardian</div>
    </div>

    <p style="text-align:center;font-size:.75rem;color:#777;margin-top:24px;">
        <?= e($reportFooter) ?>
    </p>

    <p class="no-print" style="text-align:center;margin-top:20px;">
        <button onclick="window.print()" class="btn btn-primary"><i class="bi bi-printer"></i> Print</button>
        <a href="javascript:history.back()" class="btn btn-outline-primary">Back</a>
    </p>
</div>
</body>
</html>