<?php
declare(strict_types=1);

/**
 * SMS — PDF helper
 * Uses FPDF if available, otherwise falls back to printable HTML.
 */

if (defined('SMS_PDF_LOADED')) { return; }
define('SMS_PDF_LOADED', true);

/**
 * Is FPDF available?
 */
function pdf_available(): bool
{
    return is_file(APP_ROOT . '/vendor/fpdf/fpdf.php');
}

/**
 * Get the school header array for reports.
 */
function pdf_school_header(): array
{
    return [
        'name'    => setting('school_name', 'SMS Secondary School'),
        'motto'   => setting('school_motto', ''),
        'address' => setting('school_address', ''),
        'phone'   => setting('school_phone', ''),
        'email'   => setting('school_email', ''),
        'website' => setting('school_website', ''),
        'logo'    => setting('school_logo', ''),
    ];
}

/**
 * Render a generic printable header block (HTML) for print-to-PDF pages.
 */
function pdf_header_html(string $title, string $subtitle = ''): string
{
    $s = pdf_school_header();
    $logoHtml = '';
    if ($s['logo'] && file_exists(path('uploads/school/' . $s['logo']))) {
        $logoHtml = '<img src="' . e(url('uploads/school/' . $s['logo'])) . '" alt="Logo" style="max-height:70px;">';
    }
    $html  = '<div class="pdf-header">';
    $html .= '<div class="pdf-header-left">' . $logoHtml . '</div>';
    $html .= '<div class="pdf-header-center">';
    $html .= '<h1>' . e($s['name']) . '</h1>';
    if ($s['motto']) $html .= '<p class="pdf-motto">' . e($s['motto']) . '</p>';
    if ($s['address']) $html .= '<p class="pdf-contact">' . e($s['address']) . '</p>';
    $contactLine = [];
    if ($s['phone']) $contactLine[] = $s['phone'];
    if ($s['email']) $contactLine[] = $s['email'];
    if ($s['website']) $contactLine[] = $s['website'];
    if ($contactLine) $html .= '<p class="pdf-contact">' . e(implode(' · ', $contactLine)) . '</p>';
    $html .= '</div>';
    $html .= '<div class="pdf-header-right"></div>';
    $html .= '</div>';

    $html .= '<div class="pdf-title"><h2>' . e($title) . '</h2>';
    if ($subtitle) $html .= '<p>' . e($subtitle) . '</p>';
    $html .= '</div>';

    return $html;
}

/**
 * Render a signature block (HTML).
 */
function pdf_signatures_html(array $names = []): string
{
    if (!$names) $names = ['Class Teacher', 'Head of School', 'Parent / Guardian'];
    $html = '<div class="pdf-signatures">';
    foreach ($names as $n) {
        $html .= '<div class="pdf-sig"><span>' . e($n) . '</span></div>';
    }
    $html .= '</div>';
    return $html;
}

/**
 * Get the base CSS for PDF print views.
 */
function pdf_css_url(): string
{
    return url('assets/css/pdf.css');
}

/**
 * Get current server timestamp for footers.
 */
function pdf_footer_text(): string
{
    return (setting('report_footer', '') ?: 'Generated by SMS')
        . ' · ' . date('d M Y H:i');
}